// ============================================================================
// FILE:     src/FileHarvester.Platform/Cloud/OAuth/GoogleOAuthFlow.cs
// PURPOSE:  IOAuthFlow implementation for Google (Drive scope). Composes
//           the PKCE flow, the loopback listener, and the state store.
//           Browser opening and listener creation are injectable seams so
//           the flow is testable without a browser or a real socket.
//           Storage-independent and UI-independent: the flow never reads
//           or writes ICredentialStore and never opens a dialog. The
//           Google client secret is fetched through an injected delegate
//           at each token exchange and is never stored in a field.
// RELATION: Implements IOAuthFlow. Consumed by OAuthTokenStore (C.6.4).
//           Uses PkceGoogleAuthorizationCodeFlow and UserCredential from
//           Google.Apis.Auth. State is application-owned; the PKCE
//           verifier is SDK-generated and application-stored.
// ============================================================================

using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;
using Google.Apis.Auth.OAuth2;
using Google.Apis.Auth.OAuth2.Flows;
using Google.Apis.Auth.OAuth2.Requests;
using Google.Apis.Auth.OAuth2.Responses;

namespace FileHarvester.Platform.Cloud.OAuth;

/// <summary>
/// Google OAuth 2.0 authorization flow for the Drive scope.
/// </summary>
/// <remarks>
/// <para>
/// The flow is storage-independent and UI-independent, but it is not
/// pure: <see cref="AuthorizeAsync"/> opens the system browser (via the
/// injected opener), binds a loopback listener (via the injected factory),
/// and calls Google's authorization and token endpoints.
/// </para>
/// <para>
/// The OAuth state nonce is generated by this flow and set on the
/// authorization request URL. The PKCE verifier is generated by the SDK
/// and returned through the out parameter of CreateAuthorizationCodeRequest.
/// Both are held by the <see cref="OAuthStateStore"/> keyed on the state,
/// and both are consumed on callback validation. The state is
/// one-time-use; a replay fails.
/// </para>
/// <para>
/// The Google client secret is fetched through the injected delegate at
/// the moment of each token exchange and is not retained in a field. An
/// empty secret fails before the browser opens, so no authorization code
/// is consumed against a request Google would reject.
/// </para>
/// </remarks>
internal sealed class GoogleOAuthFlow : IOAuthFlow
{
    private const string UserId = "file-ferry";

    private readonly OAuthStateStore _stateStore;
    private readonly Func<string, Task> _openBrowser;
    private readonly Func<int, string, TimeSpan, IOAuthLoopbackListener> _listenerFactory;
    private readonly Func<CancellationToken, Task<string?>> _fetchClientSecret;
    private readonly TimeSpan _callbackTimeout;

    /// <summary>
    /// Creates the flow with its injectable seams.
    /// </summary>
    /// <param name="stateStore">
    /// The state and verifier store. Not null.
    /// </param>
    /// <param name="openBrowser">
    /// Opens the authorization URL in the system browser. Not null.
    /// Production supplies a delegate that starts the browser; tests
    /// supply one that captures the URL.
    /// </param>
    /// <param name="listenerFactory">
    /// Creates the loopback listener for (port, path, timeout). Not null.
    /// Production supplies a factory that returns the real listener; tests
    /// supply one that returns a prepared listener.
    /// </param>
    /// <param name="fetchClientSecret">
    /// Fetches the Google client secret at token-exchange time. Not null.
    /// Production supplies a delegate that reads the secret from the
    /// credential store; tests supply one that returns a fixed value.
    /// </param>
    /// <param name="callbackTimeout">
    /// The maximum time to wait for the callback. Must be positive.
    /// </param>
    public GoogleOAuthFlow(
        OAuthStateStore stateStore,
        Func<string, Task> openBrowser,
        Func<int, string, TimeSpan, IOAuthLoopbackListener> listenerFactory,
        Func<CancellationToken, Task<string?>> fetchClientSecret,
        TimeSpan callbackTimeout)
    {
        _stateStore = stateStore ?? throw new ArgumentNullException(nameof(stateStore));
        _openBrowser = openBrowser ?? throw new ArgumentNullException(nameof(openBrowser));
        _listenerFactory = listenerFactory ?? throw new ArgumentNullException(nameof(listenerFactory));
        _fetchClientSecret = fetchClientSecret ?? throw new ArgumentNullException(nameof(fetchClientSecret));

        if (callbackTimeout <= TimeSpan.Zero)
        {
            throw new ArgumentOutOfRangeException(
                nameof(callbackTimeout),
                "Callback timeout must be positive.");
        }

        _callbackTimeout = callbackTimeout;
    }

    /// <inheritdoc />
    public async Task<OAuthTokens> AuthorizeAsync(
        OAuthClientConfig config,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(config);

        // The client secret is required before any browser action. Fetch
        // it first and fail closed if it is absent, so an authorization
        // code is not consumed against a token request Google would reject.
        var clientSecret = await _fetchClientSecret(cancellationToken).ConfigureAwait(false);
        if (string.IsNullOrWhiteSpace(clientSecret))
        {
            throw new InvalidOperationException(
                "The Google Client Secret has not been saved. Save it before connecting.");
        }

        var initializer = new GoogleAuthorizationCodeFlow.Initializer
        {
            ClientSecrets = new ClientSecrets
            {
                ClientId = config.ClientId,
                ClientSecret = clientSecret,
            },
            Scopes = config.Scopes,
        };

        var pkceFlow = new PkceGoogleAuthorizationCodeFlow(initializer);

        // Step 1: SDK generates the PKCE verifier and returns the auth URL.
        var authUrl = pkceFlow.CreateAuthorizationCodeRequest(config.RedirectUri, out var codeVerifier);

        // Step 2: The application generates the state nonce and sets it on
        // the URL. State and verifier are two separate values with two
        // separate owners. Both are stored under the state key.
        var state = OAuthStateStore.NewState();
        authUrl.State = state;
        _stateStore.Store(state, codeVerifier);

        // Step 3: Open the browser and await the callback.
        var port = ParsePortFromRedirectUri(config.RedirectUri);
        var callbackPath = ParsePathFromRedirectUri(config.RedirectUri);

        await using var listener = _listenerFactory(port, callbackPath, _callbackTimeout);

        var waitTask = listener.WaitForCallbackAsync(cancellationToken);
        await _openBrowser(authUrl.Build().AbsoluteUri).ConfigureAwait(false);
        var callback = await waitTask.ConfigureAwait(false);

        // Step 4: Validate the returned state. Consume removes the entry;
        // a replay fails. The verifier is recovered from the store.
        if (callback.Error is not null)
        {
            if (string.Equals(callback.Error, "access_denied", StringComparison.Ordinal))
            {
                throw new OAuthConsentDeniedException();
            }

            throw new OAuthCallbackException(callback.Error);
        }

        if (string.IsNullOrEmpty(callback.Code) || string.IsNullOrEmpty(callback.State))
        {
            throw new OAuthCallbackException(errorCode: null);
        }

        // Consume validates state match and one-time use, and returns the
        // stored verifier. A mismatch or a replay throws OAuthStateException.
        if (!string.Equals(callback.State, state, StringComparison.Ordinal))
        {
            throw new OAuthStateException("returned state did not match the issued state");
        }

        var storedVerifier = _stateStore.Consume(callback.State);

        // Step 5: Exchange the code for tokens.
        var tokenResponse = await pkceFlow.ExchangeCodeForTokenAsync(
            UserId,
            callback.Code,
            storedVerifier,
            config.RedirectUri,
            cancellationToken).ConfigureAwait(false);

        return Map(tokenResponse);
    }

    /// <inheritdoc />
    public async Task<OAuthTokens> RefreshAsync(
        OAuthClientConfig config,
        string refreshToken,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(config);
        ArgumentException.ThrowIfNullOrWhiteSpace(refreshToken);

        var clientSecret = await _fetchClientSecret(cancellationToken).ConfigureAwait(false);
        if (string.IsNullOrWhiteSpace(clientSecret))
        {
            throw new InvalidOperationException(
                "The Google Client Secret has not been saved. Save it before connecting.");
        }

        var initializer = new GoogleAuthorizationCodeFlow.Initializer
        {
            ClientSecrets = new ClientSecrets
            {
                ClientId = config.ClientId,
                ClientSecret = clientSecret,
            },
            Scopes = config.Scopes,
        };

        var pkceFlow = new PkceGoogleAuthorizationCodeFlow(initializer);
        var existing = new TokenResponse { RefreshToken = refreshToken };
        var credential = new UserCredential(pkceFlow, UserId, existing);

        try
        {
            await credential.RefreshTokenAsync(cancellationToken).ConfigureAwait(false);
        }
        catch (TokenResponseException ex) when (string.Equals(ex.Error?.Error, "invalid_grant", StringComparison.Ordinal))
        {
            throw new OAuthTokenRevokedException();
        }

        return Map(credential.Token);
    }

    /// <inheritdoc />
    public async Task RevokeAsync(
        OAuthClientConfig config,
        string refreshToken,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(config);
        ArgumentException.ThrowIfNullOrWhiteSpace(refreshToken);

        var clientSecret = await _fetchClientSecret(cancellationToken).ConfigureAwait(false);
        if (string.IsNullOrWhiteSpace(clientSecret))
        {
            throw new InvalidOperationException(
                "The Google Client Secret has not been saved. Save it before connecting.");
        }

        var initializer = new GoogleAuthorizationCodeFlow.Initializer
        {
            ClientSecrets = new ClientSecrets
            {
                ClientId = config.ClientId,
                ClientSecret = clientSecret,
            },
            Scopes = config.Scopes,
        };

        var pkceFlow = new PkceGoogleAuthorizationCodeFlow(initializer);
        var existing = new TokenResponse { RefreshToken = refreshToken };
        var credential = new UserCredential(pkceFlow, UserId, existing);

        await credential.RevokeTokenAsync(cancellationToken).ConfigureAwait(false);
    }

    // ------------------------------------------------------------------
    // Helpers.
    // ------------------------------------------------------------------

    /// <summary>
    /// Maps the SDK's TokenResponse to the C.6 OAuthTokens record.
    /// Computes the absolute expiry instant from the issued time and
    /// ExpiresInSeconds.
    /// </summary>
    private static OAuthTokens Map(TokenResponse token)
    {
        var issuedUtc = token.IssuedUtc;
        var expiresAt = token.ExpiresInSeconds is { } seconds
            ? issuedUtc.AddSeconds(seconds)
            : issuedUtc;

        return new OAuthTokens(
            AccessToken: token.AccessToken ?? string.Empty,
            ExpiresAtUtc: expiresAt,
            RefreshToken: token.RefreshToken,
            Scope: token.Scope);
    }

    private static int ParsePortFromRedirectUri(string redirectUri)
    {
        var uri = new Uri(redirectUri, UriKind.Absolute);
        return uri.Port;
    }

    private static string ParsePathFromRedirectUri(string redirectUri)
    {
        var uri = new Uri(redirectUri, UriKind.Absolute);
        return uri.AbsolutePath;
    }
}
